-- Butchery workspace: shared shop-scoped configuration, cuts, sales and atomic stock.

CREATE TABLE IF NOT EXISTS public.butchery_config (
  shop_id uuid PRIMARY KEY REFERENCES public.shops(id) ON DELETE CASCADE,
  enabled boolean NOT NULL DEFAULT false,
  butchery_name text NOT NULL DEFAULT '',
  beef_only_mode boolean NOT NULL DEFAULT false,
  default_beef_price_per_kg_ksh integer NOT NULL DEFAULT 680 CHECK (default_beef_price_per_kg_ksh >= 0),
  payment_methods jsonb NOT NULL DEFAULT '["M-Pesa", "Cash Payment"]'::jsonb,
  enabled_categories jsonb NOT NULL DEFAULT '["Beef", "Goat/Mbuzi", "Chicken", "Liver/Matumbo", "Pork"]'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.butchery_cuts (
  id text PRIMARY KEY,
  shop_id uuid NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
  name text NOT NULL,
  category text NOT NULL,
  icon_key text NOT NULL DEFAULT 'beef_steak',
  price_per_kg_ksh integer NOT NULL DEFAULT 0 CHECK (price_per_kg_ksh >= 0),
  stock_grams integer NOT NULL DEFAULT 0 CHECK (stock_grams >= 0),
  active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT butchery_cuts_shop_id_id_key UNIQUE (shop_id, id)
);
CREATE INDEX IF NOT EXISTS butchery_cuts_shop_sort_idx ON public.butchery_cuts(shop_id, sort_order, name);
CREATE INDEX IF NOT EXISTS butchery_cuts_shop_active_idx ON public.butchery_cuts(shop_id, active);

CREATE TABLE IF NOT EXISTS public.butchery_sales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shop_id uuid NOT NULL REFERENCES public.shops(id) ON DELETE CASCADE,
  operation_id text NOT NULL,
  cut_id text NOT NULL,
  cut_name text NOT NULL,
  category text NOT NULL,
  price_per_kg_ksh integer NOT NULL CHECK (price_per_kg_ksh >= 0),
  weight_grams integer NOT NULL CHECK (weight_grams > 0),
  total_ksh integer NOT NULL CHECK (total_ksh >= 0),
  payment_method text NOT NULL,
  entry_mode text NOT NULL,
  stock_deducted_grams integer NOT NULL DEFAULT 0 CHECK (stock_deducted_grams >= 0),
  attendant_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  attendant_name text,
  created_at timestamptz NOT NULL DEFAULT now(),
  undone boolean NOT NULL DEFAULT false,
  undone_at timestamptz,
  CONSTRAINT butchery_sales_operation_key UNIQUE (shop_id, operation_id)
);
CREATE INDEX IF NOT EXISTS butchery_sales_shop_created_idx ON public.butchery_sales(shop_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS butchery_sales_shop_undone_created_idx ON public.butchery_sales(shop_id, undone, created_at DESC);

ALTER TABLE public.butchery_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.butchery_cuts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.butchery_sales ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "butchery members read config" ON public.butchery_config;
CREATE POLICY "butchery members read config" ON public.butchery_config FOR SELECT TO authenticated
  USING (public.is_platform_admin() OR public.is_shop_member(shop_id));
DROP POLICY IF EXISTS "butchery members read cuts" ON public.butchery_cuts;
CREATE POLICY "butchery members read cuts" ON public.butchery_cuts FOR SELECT TO authenticated
  USING (public.is_platform_admin() OR public.is_shop_member(shop_id));
DROP POLICY IF EXISTS "butchery members read sales" ON public.butchery_sales;
CREATE POLICY "butchery members read sales" ON public.butchery_sales FOR SELECT TO authenticated
  USING (public.is_platform_admin() OR public.is_shop_member(shop_id));

-- Writes are intentionally RPC-only. The procedures below validate both tenant membership and role.
REVOKE INSERT, UPDATE, DELETE ON public.butchery_config FROM authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.butchery_cuts FROM authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.butchery_sales FROM authenticated;
GRANT SELECT ON public.butchery_config, public.butchery_cuts, public.butchery_sales TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.butchery_sales_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.butchery_seed_cuts(_shop uuid, _price integer)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.butchery_cuts(id, shop_id, name, category, icon_key, price_per_kg_ksh, sort_order)
  VALUES
    (_shop::text || '_beef', _shop, 'Beef', 'Beef', 'beef', _price, 10),
    (_shop::text || '_goat', _shop, 'Goat/Mbuzi', 'Goat/Mbuzi', 'goat', _price, 20),
    (_shop::text || '_chicken', _shop, 'Chicken', 'Chicken', 'chicken', _price, 30),
    (_shop::text || '_liver', _shop, 'Liver/Matumbo', 'Liver/Matumbo', 'liver', _price, 40),
    (_shop::text || '_pork', _shop, 'Pork', 'Pork', 'pork', _price, 50)
  ON CONFLICT (id) DO NOTHING;
END $$;

CREATE OR REPLACE FUNCTION public.upsert_butchery_config(
  _shop uuid,
  _enabled boolean DEFAULT false,
  _butchery_name text DEFAULT '',
  _beef_only_mode boolean DEFAULT false,
  _default_beef_price_per_kg_ksh integer DEFAULT 680,
  _payment_methods jsonb DEFAULT '["M-Pesa", "Cash Payment"]'::jsonb,
  _enabled_categories jsonb DEFAULT '["Beef", "Goat/Mbuzi", "Chicken", "Liver/Matumbo", "Pork"]'::jsonb
)
RETURNS public.butchery_config LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE result public.butchery_config;
BEGIN
  IF NOT public.is_shop_manager(_shop) AND NOT public.is_platform_admin() THEN RAISE EXCEPTION 'forbidden'; END IF;
  IF _default_beef_price_per_kg_ksh < 0 THEN RAISE EXCEPTION 'invalid_price'; END IF;
  INSERT INTO public.butchery_config(shop_id, enabled, butchery_name, beef_only_mode, default_beef_price_per_kg_ksh, payment_methods, enabled_categories, updated_at)
  VALUES (_shop, coalesce(_enabled, false), coalesce(trim(_butchery_name), ''), coalesce(_beef_only_mode, false), _default_beef_price_per_kg_ksh,
          coalesce(_payment_methods, '[]'::jsonb), coalesce(_enabled_categories, '[]'::jsonb), now())
  ON CONFLICT (shop_id) DO UPDATE SET enabled = EXCLUDED.enabled, butchery_name = EXCLUDED.butchery_name,
    beef_only_mode = EXCLUDED.beef_only_mode, default_beef_price_per_kg_ksh = EXCLUDED.default_beef_price_per_kg_ksh,
    payment_methods = EXCLUDED.payment_methods, enabled_categories = EXCLUDED.enabled_categories, updated_at = now()
  RETURNING * INTO result;
  IF result.enabled AND NOT EXISTS (SELECT 1 FROM public.butchery_cuts WHERE shop_id = _shop) THEN
    PERFORM public.butchery_seed_cuts(_shop, result.default_beef_price_per_kg_ksh);
  END IF;
  PERFORM public.write_audit_event(_shop, 'butchery_config_updated', 'butchery_config', NULL,
    jsonb_build_object('enabled', result.enabled));
  RETURN result;
END $$;

CREATE OR REPLACE FUNCTION public.upsert_butchery_cut(
  _shop uuid, _id text, _name text, _category text, _price_per_kg_ksh integer,
  _stock_grams integer DEFAULT 0, _icon_key text DEFAULT 'beef_steak', _active boolean DEFAULT true, _sort_order integer DEFAULT 0
)
RETURNS public.butchery_cuts LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE result public.butchery_cuts;
BEGIN
  IF NOT public.is_shop_manager(_shop) AND NOT public.is_platform_admin() THEN RAISE EXCEPTION 'forbidden'; END IF;
  IF nullif(trim(_id), '') IS NULL OR nullif(trim(_name), '') IS NULL OR nullif(trim(_category), '') IS NULL THEN RAISE EXCEPTION 'invalid_cut'; END IF;
  IF _price_per_kg_ksh < 0 OR _stock_grams < 0 THEN RAISE EXCEPTION 'invalid_cut_values'; END IF;
  INSERT INTO public.butchery_cuts(id, shop_id, name, category, price_per_kg_ksh, stock_grams, icon_key, active, sort_order, updated_at)
  VALUES (_id, _shop, trim(_name), trim(_category), _price_per_kg_ksh, _stock_grams, coalesce(nullif(trim(_icon_key), ''), 'beef_steak'), coalesce(_active, true), coalesce(_sort_order, 0), now())
  ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, category = EXCLUDED.category, price_per_kg_ksh = EXCLUDED.price_per_kg_ksh,
    stock_grams = EXCLUDED.stock_grams, icon_key = EXCLUDED.icon_key, active = EXCLUDED.active, sort_order = EXCLUDED.sort_order, updated_at = now()
  WHERE public.butchery_cuts.shop_id = _shop
  RETURNING * INTO result;
  IF result.id IS NULL THEN RAISE EXCEPTION 'cut_not_found'; END IF;
  PERFORM public.write_audit_event(_shop, 'butchery_cut_updated', 'butchery_cut', NULL, jsonb_build_object('cut_id', result.id));
  RETURN result;
END $$;

CREATE OR REPLACE FUNCTION public.update_butchery_category_price(_shop uuid, _category text, _price_per_kg_ksh integer)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE changed integer;
BEGIN
  IF NOT public.is_shop_manager(_shop) AND NOT public.is_platform_admin() THEN RAISE EXCEPTION 'forbidden'; END IF;
  IF _price_per_kg_ksh < 0 THEN RAISE EXCEPTION 'invalid_price'; END IF;
  UPDATE public.butchery_cuts SET price_per_kg_ksh = _price_per_kg_ksh, updated_at = now()
  WHERE shop_id = _shop AND lower(category) = lower(trim(_category));
  GET DIAGNOSTICS changed = ROW_COUNT;
  IF changed > 0 THEN PERFORM public.write_audit_event(_shop, 'butchery_category_price_updated', 'butchery_cut', NULL,
    jsonb_build_object('category', _category, 'price_per_kg_ksh', _price_per_kg_ksh, 'changed', changed)); END IF;
  RETURN changed;
END $$;

CREATE OR REPLACE FUNCTION public.record_butchery_sale(
  _shop uuid, _cut_id text, _weight_grams integer, _payment_method text, _entry_mode text,
  _operation_id text DEFAULT NULL, _cut_name text DEFAULT NULL, _category text DEFAULT NULL,
  _price_per_kg_ksh integer DEFAULT NULL, _total_ksh integer DEFAULT NULL, _attendant_name text DEFAULT NULL
)
RETURNS public.butchery_sales LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE cut_row public.butchery_cuts; existing public.butchery_sales; result public.butchery_sales;
DECLARE total_value integer; operation_key text;
BEGIN
  IF NOT public.has_shop_role(_shop, ARRAY['owner','manager','cashier']::public.shop_role[]) AND NOT public.is_platform_admin() THEN RAISE EXCEPTION 'forbidden'; END IF;
  IF _weight_grams IS NULL OR _weight_grams <= 0 THEN RAISE EXCEPTION 'invalid_weight'; END IF;
  operation_key := coalesce(nullif(trim(_operation_id), ''), gen_random_uuid()::text);
  SELECT * INTO existing FROM public.butchery_sales WHERE shop_id = _shop AND operation_id = operation_key;
  IF existing.id IS NOT NULL THEN
    IF existing.cut_id <> _cut_id OR existing.weight_grams <> _weight_grams OR existing.total_ksh <> coalesce(_total_ksh, existing.total_ksh) THEN RAISE EXCEPTION 'operation_payload_mismatch'; END IF;
    RETURN existing;
  END IF;
  SELECT * INTO cut_row FROM public.butchery_cuts WHERE id = _cut_id AND shop_id = _shop AND active FOR UPDATE;
  IF cut_row.id IS NULL THEN RAISE EXCEPTION 'cut_not_found'; END IF;
  IF cut_row.stock_grams < _weight_grams THEN RAISE EXCEPTION 'insufficient_stock'; END IF;
  total_value := coalesce(_total_ksh, ((_weight_grams::numeric * coalesce(_price_per_kg_ksh, cut_row.price_per_kg_ksh) / 1000)::numeric)::integer);
  IF total_value < 0 THEN RAISE EXCEPTION 'invalid_total'; END IF;
  UPDATE public.butchery_cuts SET stock_grams = stock_grams - _weight_grams, updated_at = now() WHERE id = cut_row.id;
  INSERT INTO public.butchery_sales(shop_id, operation_id, cut_id, cut_name, category, price_per_kg_ksh, weight_grams, total_ksh, payment_method, entry_mode, stock_deducted_grams, attendant_user_id, attendant_name)
  VALUES (_shop, operation_key, cut_row.id, coalesce(nullif(trim(_cut_name), ''), cut_row.name), coalesce(nullif(trim(_category), ''), cut_row.category), coalesce(_price_per_kg_ksh, cut_row.price_per_kg_ksh), _weight_grams, total_value, coalesce(nullif(trim(_payment_method), ''), 'cash'), coalesce(nullif(trim(_entry_mode), ''), 'weight'), _weight_grams, auth.uid(), nullif(trim(_attendant_name), ''))
  RETURNING * INTO result;
  PERFORM public.write_audit_event(_shop, 'butchery_sale_recorded', 'butchery_sale', NULL, jsonb_build_object('sale_id', result.id, 'cut_id', result.cut_id, 'weight_grams', result.weight_grams, 'operation_id', result.operation_id));
  RETURN result;
EXCEPTION WHEN unique_violation THEN
  SELECT * INTO existing FROM public.butchery_sales WHERE shop_id = _shop AND operation_id = operation_key;
  IF existing.id IS NOT NULL THEN RETURN existing; END IF;
  RAISE;
END $$;

CREATE OR REPLACE FUNCTION public.undo_latest_butchery_sale(_shop uuid, _sale_id bigint DEFAULT NULL)
RETURNS public.butchery_sales LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE sale_row public.butchery_sales; result public.butchery_sales;
BEGIN
  IF NOT public.is_shop_manager(_shop) AND NOT public.is_platform_admin() THEN RAISE EXCEPTION 'forbidden'; END IF;
  IF _sale_id IS NULL THEN SELECT * INTO sale_row FROM public.butchery_sales WHERE shop_id = _shop AND NOT undone ORDER BY created_at DESC, id DESC LIMIT 1 FOR UPDATE;
  ELSE SELECT * INTO sale_row FROM public.butchery_sales WHERE shop_id = _shop AND id = _sale_id FOR UPDATE; END IF;
  IF sale_row.id IS NULL THEN RAISE EXCEPTION 'nothing_to_undo'; END IF;
  IF sale_row.undone THEN RETURN sale_row; END IF;
  UPDATE public.butchery_cuts SET stock_grams = stock_grams + sale_row.stock_deducted_grams, updated_at = now() WHERE id = sale_row.cut_id AND shop_id = _shop;
  IF NOT FOUND THEN RAISE EXCEPTION 'cut_not_found'; END IF;
  UPDATE public.butchery_sales SET undone = true, undone_at = now() WHERE id = sale_row.id RETURNING * INTO result;
  PERFORM public.write_audit_event(_shop, 'butchery_sale_undone', 'butchery_sale', NULL, jsonb_build_object('sale_id', result.id, 'restored_grams', result.stock_deducted_grams));
  RETURN result;
END $$;

CREATE OR REPLACE FUNCTION public.get_butchery_daily_sales_trend(_shop uuid, _from date DEFAULT (current_date - 30), _to date DEFAULT current_date)
RETURNS TABLE(sale_date date, sale_count bigint, total_ksh bigint, weight_grams bigint)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT created_at::date, count(*) FILTER (WHERE NOT undone), coalesce(sum(total_ksh) FILTER (WHERE NOT undone), 0), coalesce(sum(weight_grams) FILTER (WHERE NOT undone), 0)
  FROM public.butchery_sales
  WHERE shop_id = _shop
    AND (public.is_platform_admin() OR public.is_shop_member(_shop))
    AND created_at::date BETWEEN _from AND _to
  GROUP BY created_at::date ORDER BY created_at::date;
$$;

